    private void submitBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_submitBtnActionPerformed
        // TODO add your handling code here:
        String namaMk = mk.getText().trim(); // trim buat ignore whitespace
        String Sks = sks.getText().trim();
        String code = kodeMk.getText().trim();

//       try and catch 
        try {
//    make sure all field are filled || &&  or atau and
            if (namaMk.isEmpty() || Sks.isEmpty() || code.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Semua field harus diisi", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
            
            daftarMatkul.add(new Matkul(namaMk , Integer.parseInt(Sks) , code));
            refreshTable();
            
            
            JOptionPane.showMessageDialog(this, "Data Matkul berhasil ditambah");
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,"Format SKS Harus angkat", "Error" ,JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_submitBtnActionPerformed

