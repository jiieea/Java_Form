    private void refreshTable() {
        tableModel.setRowCount(0); //reset baris
        for (Matkul m : daftarMatkul) { // m represent the elements of Matkul; 
            tableModel.addRow(new Object[]{ // add new row
                m.getNamaMk(), m.getKodeMk(), m.getSks()
            });
        }
    }

