    private void refreshTable() {
        tableModel.setRowCount(0);
        for (Mahasiswa m : daftarMahasiswa) {
            tableModel.addRow(new Object[]{
                m.getNim(), m.getNama(), m.getIpk(), m.getAngkatan(), m.getStatus()
            });
        }
    }

